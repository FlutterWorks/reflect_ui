import 'package:reflect_ui/src/core/widget_variant.dart';

/// The variant of a button.
enum ButtonVariant with WidgetVariant {
  /// A filled button.
  filled,

  /// A tinted button.
  tinted,

  /// An outlined button.
  outlined,

  /// A subtle button.
  subtle,

  /// A plain button.
  plain,
}
